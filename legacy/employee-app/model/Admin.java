package com.employee.model;

public class Admin {

    private int id;

    private String name;

    // No-arg constructor
    public Admin() {
    }

    // Getters and setters
    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}



